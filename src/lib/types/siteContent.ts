export function getPageCopyDefaults(pageId: PublicPageId, locale: Locale): PublicPageCopy {
  // Segmentos que não são idioma (ex.: /robots.txt) caem em [locale]; o layout responde 404,
  // mas a página pode renderizar antes — o português evita o erro 500 nesse meio-tempo.
  return (DEFAULT_PUBLIC_CONTENT[locale] ?? DEFAULT_PUBLIC_CONTENT.pt)[pageId];
}

// Imagens do site vêm do próprio domínio (upload em /api/site-media ou /public).
export function isSafeLocalImagePath(value: string): boolean {
  return /^\/(?!\/)[A-Za-z0-9/_\-.]+$/.test(value) && !value.split("/").includes("..");
}

export function isPublicPageId(value: unknown): value is PublicPageId {
  return typeof value === "string" && PUBLIC_PAGE_IDS.includes(value as PublicPageId);
}

export function isPublicPageCopy(value: unknown, pageId: PublicPageId, locale: Locale): value is PublicPageCopy {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
  const allowedFields = Object.keys(getPageCopyDefaults(pageId, locale));
  return allowedFields.every((key) => {
    const fieldValue = Reflect.get(value, key);
    if (typeof fieldValue !== "string" || fieldValue.length > 5000) return false;
    if (key === "imageUrl") return fieldValue === "" || isSafeLocalImagePath(fieldValue);
    if (key === "imageAlt" && Reflect.get(value, "imageUrl") !== "" && fieldValue.trim() === "") {
      return false;
    }
    return true;
  }) && Object.keys(value).every((key) => allowedFields.includes(key));
}
